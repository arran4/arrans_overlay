#!/usr/bin/env python3
"""Create reviewable Gentoo source ebuilds for real KLookup releases.

Run from the root of arrans_overlay. GitHub Actions creates the PR from the
resulting working-tree diff; this script never pushes or creates a PR itself.
"""

import json
import os
from pathlib import Path
import re
import subprocess
import urllib.request

PACKAGE_DIR = Path('app-misc/klookup')
LIVE_EBUILD = PACKAGE_DIR / 'klookup-9999.ebuild'
RELEASES_URL = 'https://api.github.com/repos/arran4/klookup/releases?per_page=100'
STABLE_TAG = re.compile(r'^v?(?P<version>[0-9]+\.[0-9]+\.[0-9]+)$')


def get_releases():
    headers = {'Accept': 'application/vnd.github+json',
               'User-Agent': 'arrans-overlay-klookup-source-updater'}
    if os.environ.get('GITHUB_TOKEN'):
        headers['Authorization'] = f"Bearer {os.environ['GITHUB_TOKEN']}"
    req = urllib.request.Request(RELEASES_URL, headers=headers)
    with urllib.request.urlopen(req, timeout=30) as response:
        releases = json.load(response)
    if not isinstance(releases, list):
        raise ValueError('GitHub releases API did not return an array')
    return releases


def eligible_releases(releases):
    seen = set()
    for release in releases:
        if not isinstance(release, dict) or release.get('draft') or release.get('prerelease'):
            continue
        tag = release.get('tag_name')
        match = STABLE_TAG.fullmatch(tag) if isinstance(tag, str) else None
        if match is None:
            continue
        version = match.group('version')
        if version in seen:
            continue
        seen.add(version)
        yield tag, version


def release_ebuild(tag, version):
    """Reuse the live ebuild's tested dependency list rather than drifting."""
    source = LIVE_EBUILD.read_text(encoding='utf-8')
    if 'inherit cmake git-r3' not in source:
        raise ValueError('Live ebuild layout changed: review source template')
    if 'EGIT_REPO_URI="https://github.com/arran4/klookup.git"' not in source:
        raise ValueError('Live ebuild Git URL changed: review release template')
    source = source.replace('inherit cmake git-r3', 'inherit cmake', 1)
    source = source.replace(
        'EGIT_REPO_URI="https://github.com/arran4/klookup.git"',
        'SRC_URI="https://github.com/arran4/klookup/archive/refs/tags/'
        f'{tag}.tar.gz -> ${{P}}.tar.gz"\nS="${{WORKDIR}}/klookup-${{PV}}"',
        1,
    )
    source = source.replace('KEYWORDS=""', 'KEYWORDS="~amd64"', 1)
    return '# Generated by scripts/update_klookup_source.py\n' + source


def create_release(tag, version):
    dest = PACKAGE_DIR / f'klookup-{version}.ebuild'
    if dest.exists():
        return False
    content = release_ebuild(tag, version)
    dest.write_text(content, encoding='utf-8')
    url = f'https://github.com/arran4/klookup/archive/refs/tags/{tag}.tar.gz'
    subprocess.run(
        ['g2', 'manifest', 'upsert-from-url', url,
         f'klookup-{version}.tar.gz', str(PACKAGE_DIR / 'Manifest')],
        check=True,
    )
    return True


def main():
    if not LIVE_EBUILD.is_file():
        raise FileNotFoundError(f'Run from overlay root: missing {LIVE_EBUILD}')
    updated = False
    for tag, version in eligible_releases(get_releases()):
        updated = create_release(tag, version) or updated
    if updated:
        subprocess.run(['g2', 'cache', 'generate', 'app-misc/klookup'], check=True)
    else:
        print('No new eligible KLookup releases')


if __name__ == '__main__':
    main()
